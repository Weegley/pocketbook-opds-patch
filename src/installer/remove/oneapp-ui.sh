#!/bin/sh
# One public application; root is used only to stage a protected boot job.
set -u
PATH=/sbin:/bin:/usr/sbin:/usr/bin
export PATH
unset LD_PRELOAD LD_LIBRARY_PATH ENV BASH_ENV
umask 077
. "$(dirname -- "$0")/i18n.sh"
case "${OPDS_UI_LANGUAGE:-}" in ru|en) :;; *) opds_select_language;; esac
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd) || exit 1
CACHE=${HERE%/scripts}
USERDIR=/mnt/ext1/system/.opds-authors-611-open
PENDING=$USERDIR/pending
ROOT_HELPER=/mnt/secure/su
ORIGINAL=e8ee93b531b4019500ea06f571028330ce3b331f6970b581caaa874295f73a98
PATCHED=c6a4b5bc1e119e4e2c1ff0cc14fb56766448995ca61ba7743f5428e4d30269f5
SU_HASH=7babf251fc0f16dfba19c4f36305e280d5e2480b94100d1e6f16bcd564cc9fbb
hash() { sha256sum "$1" | awk '{print $1}'; }
notice() { dialog 1 OPDS "$1" OK >/dev/null 2>&1 || :; }
ask() { dialog 2 OPDS "$1" "$2" "$(opds_text cancel)" >/dev/null 2>&1; [ "$?" = 1 ]; }
finish() {
    code=$?
    trap - EXIT HUP INT TERM
    sync
    # Only this invocation's mktemp directory is removable, never USERDIR/state.
    case "$CACHE" in "$USERDIR"/run.*) rm -rf "$CACHE";; esac
    exit "$code"
}
trap finish EXIT
trap 'exit 130' HUP INT TERM
exec 8> "$USERDIR/ui.guard"
flock -n 8 || { notice "$(opds_text busy)"; exit 1; }
[ "$(cat /ebrmain/.version)" = ver=6.11.2001 ] &&
grep -qx model=Pocket632 /ebrmain/config/device.cfg &&
grep -qx variant=U632 /ebrmain/config/device.cfg || { notice "$(opds_text wrong_firmware)"; exit 1; }
[ "$(hash /ebrmain/cramfs/lib/libopds_app_lib.so)" = "$ORIGINAL" ] || { notice "$(opds_text original_mismatch)"; exit 1; }
current=$(hash /ebrmain/lib/libopds_app_lib.so)
case "$current" in "$ORIGINAL"|"$PATCHED") :;; *) notice "$(opds_text unknown_library)"; exit 1;; esac
. "$HERE/prepare-library.sh"
prepare_library "$CACHE/payload" "$CACHE" || { notice "$(opds_text prepare_failed)"; exit 1; }
# Explicit consent is required even when resuming a pending operation.
if [ -e "$ROOT_HELPER" ] || [ -L "$ROOT_HELPER" ]; then
    ask "$(opds_text existing_root_warning)" "$(opds_text confirm_remove_root)" || exit 0
fi
action=
if [ -f "$PENDING" ] && [ ! -L "$PENDING" ]; then
    action=$(cat "$PENDING")
    case "$action" in install|uninstall) :;; *) notice "$(opds_text bad_state)"; exit 1;; esac
    # Reconcile an interrupted final receipt using current files, not old logs.
    if [ -d /mnt/secure ] && [ -x /mnt/secure ] && [ ! -e "$ROOT_HELPER" ] && [ ! -L "$ROOT_HELPER" ]; then
        if [ -f "$USERDIR/rolled-back" ] && [ "$(cat "$USERDIR/rolled-back")" = "$action" ] && [ "$current" = "$ORIGINAL" ]; then
            rm -f "$PENDING"
            notice "$(opds_text rolled_back)"
            exit 1
        fi
        expected=$ORIGINAL
        [ "$action" != install ] || expected=$PATCHED
        if [ "$current" = "$expected" ] && awk '$2=="/ebrmain" && $4 ~ /(^|,)ro(,|$)/ {ok=1} END {exit !ok}' /proc/mounts; then
            LOG=/mnt/ext1/OPDS_Non_rooted_611_${action}.log
            { echo '=== Reconciled completion ==='; date; echo "RESULT=DISK_VERIFIED_ROOT_ABSENT action=$action"; echo 'RUNTIME_MAPPING=not checked; this is not a live Explorer verification.'; } >> "$LOG"
            rm -f "$PENDING"
            notice "$(opds_text completed)"
            exit 0
        fi
    fi
else
    if [ "$current" = "$ORIGINAL" ]; then
        action=install
        ask "$(opds_text install_remove_root)" "$(opds_text install)" || exit 0
    else
        action=uninstall
        ask "$(opds_text uninstall_remove_root)" "$(opds_text uninstall)" || exit 0
    fi
    rm -f "$USERDIR/rolled-back"
    printf '%s\n' "$action" > "$PENDING.new" && mv -f "$PENDING.new" "$PENDING" || exit 1
    sync
fi
LOG=/mnt/ext1/OPDS_Non_rooted_611_${action}.log
[ ! -L "$LOG" ] || { notice "$(opds_text log_symlink)"; exit 1; }
exec >> "$LOG" 2>&1
echo '=== New invocation: Non-rooted patch open v9 UI ==='
echo "ACTION=$action"
date
id
echo "CURRENT_SHA256=$current"
if [ ! -x "$ROOT_HELPER" ]; then
    . "$HERE/pbjb-components.sh"
    opds_get_pbjb "$CACHE" || { notice "$(opds_text pbjb_missing)"; exit 1; }
    echo 'ROOT_REQUIRED: using the unchanged pbjb jailbreak [cmd] interface.'
    sync
    # The upstream CLI explicitly accepts one command string (jailbreak.c main).
    # All shell arguments below are fixed or generated by our own mktemp.
    printf '%s\n' "$HERE" | grep -Eq '^/mnt/ext1/system/\.opds-authors-611-open/run\.[A-Za-z0-9]{6}/scripts$' || exit 1
    [ ! -L "$ROOT_HELPER" ] || { notice "$(opds_text helper_symlink)"; exit 1; }
    rm -f /var/tmp/su /var/tmp/jailbreak || exit 1
    cp "$CACHE/pbjb/su" /var/tmp/su && cp "$CACHE/pbjb/jailbreak" /var/tmp/jailbreak || exit 1
    chmod 755 /var/tmp/su /var/tmp/jailbreak || exit 1
    [ "$(hash /var/tmp/su)" = "$SU_HASH" ] &&
    [ "$(hash /var/tmp/jailbreak)" = a523b9e77519fa0dd657268c4ad59d3ea1bcb4e07355687e6e372b68ff8c6a10 ] || exit 1
    iv2sh SetActiveTask "$(pidof bookshelf.app)" 0 >/dev/null 2>&1 || :
    notice "$(opds_text bootstrap)"
    /var/tmp/jailbreak "/bin/sh '$HERE/oneapp-root.sh' bootstrap '$action'" 8>&-
    code=$?
    echo "JAILBREAK_RETURNED=$code"
    echo 'RESULT=BOOTSTRAP_RETURNED; no automatic completion is claimed. Inspect this log.'
    notice "$(opds_text bootstrap_returned)"
    exit "$code"
fi
if [ -L "$ROOT_HELPER" ] || [ "$(hash "$ROOT_HELPER")" != "$SU_HASH" ]; then
    echo 'RESULT=REFUSED: root helper differs from the embedded v8 helper.'
    notice "$(opds_text foreign_helper_remove)"
    exit 1
fi
# FD8 belongs only to this UI. Do not let root descendants retain its lock.
"$ROOT_HELPER" /bin/sh "$HERE/oneapp-root.sh" stage "$action" remove-existing-root-confirmed 8>&-
code=$?
echo "STAGE_EXIT=$code"
if [ "$code" != 0 ]; then
    echo 'RESULT=STAGE_FAILED; root was not removed; inspect the log.'
    notice "$(opds_text stage_failed)"
    exit "$code"
fi
echo 'RESULT=QUEUED; boot will perform the operation and remove root before Explorer.'
sync
notice "$(opds_text queued_remove)"
sync
iv2sh reboot
echo 'REBOOT_REQUEST_RETURNED: if no reboot occurs, reboot normally; do not launch old Install/Keep/Restore apps.'
exit 0
